import type { CopyOverlay } from "./keys";

// M3.9 片 b —— 繁体中文**覆盖层**（不是一套完整界面文案）。
//
// **为什么存在**：片 a 的母语猜测横幅本来就写了繁体那一版（那句话必须用**猜出来的
// 那门语言**说，不然它自我否定）。建文案表时若只留 zh-Hans + en 两套，
// 繁体使用者那句话就会倒退成简体 —— **已经交付的东西不该因为重构而变差**。
//
// **为什么不做成完整的一套**：整站繁体要逐条人工写，不在本片范围内，
// 而机械转换出来的"伪繁体"正是 D42 明令不做的那种假支持。
// 所以它是覆盖层：写了的用它，没写的落回简体。
//
// **也因此它不出现在「界面语言」选择器里** —— 选择器只列**完整**的两套。
// 列一个残缺的选项 = 用户选了之后看到半简半繁，那比不给这个选项更糟。

export const zhHant: CopyOverlay = {
  "lang.guess.lead": (label: string) => `你的母語現在是「${label}」，是照你裝置的語言自動填的。`,
  "lang.guess.cta": "不對就去改",
  "lang.guess.close": "知道了，別再提",
};
